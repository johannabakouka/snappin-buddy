/**
 * Les langues que l'app parle.
 *
 * C'était une suite de `if` à rallonge : ajouter une langue demandait de
 * penser à venir modifier cette fonction, et une langue traduite mais oubliée
 * ici restait invisible. La liste est maintenant la seule source de vérité.
 *
 * Ajouter une langue tient donc en trois gestes : un bloc dans `translations`
 * ci-dessus, un bloc dans tx-dict.js, et son code ici.
 */
export const LANGUES = [
  'fr', 'en', 'es', 'pt', 'de', 'it',
  'nl', 'pl', 'tr', 'id', 'sv', 'da', 'nb', 'fi', 'cs', 'ro', 'hu', 'vi',
];

export function getLang() {
  if (typeof window === 'undefined') return 'fr';
  const brut = (navigator.language || 'fr').toLowerCase();
  const code = brut.split('-')[0];
  if (LANGUES.includes(code)) return code;
  // Le norvégien s'annonce « no », « nb » ou « nn » selon le téléphone.
  if (code === 'no' || code === 'nn') return 'nb';
  return 'en';
}

export function useT() {
  const lang = getLang();
  return translations[lang] || translations.en;
}

export function useRoles() {
  const lang = getLang();
  return lang === 'fr' ? ROLES_FR : ROLES_EN;
}

export function useUnivers() {
  const lang = getLang();
  return lang === 'fr' ? UNIVERS_FR : UNIVERS_EN;
}